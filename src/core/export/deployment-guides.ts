import { SiteConfiguration } from "@/core/schema/site-config";
import { ExportOutputFile } from "./types";

/**
 * Fortress AI — Multi-Host Deployment Configuration Generator (TDD §21.2, §36.1, FR-080)
 * Generates platform-specific configuration files (Netlify, Vercel, Cloudflare, GitHub Pages, Nginx, Apache)
 * and a complete deployment README.md for the static export bundle.
 */

export function generateDeploymentConfigs(
  config: SiteConfiguration,
  routes: string[]
): ExportOutputFile[] {
  const files: ExportOutputFile[] = [];

  // 1. Netlify: _redirects & netlify.toml
  const netlifyRedirects = `# Netlify Clean URLs & 404 Fallback (TDD §21.2)
${routes
  .filter((r) => r !== "/")
  .map((r) => `${r} ${r}.html 200`)
  .join("\n")}
/* /index.html 200
`;
  files.push({
    path: "_redirects",
    content: netlifyRedirects,
    contentType: "text/plain",
  });

  const netlifyToml = `# Netlify Configuration (TDD §21.2)
[build]
  publish = "."

[[headers]]
  for = "/*"
  [headers.values]
    X-Frame-Options = "DENY"
    X-Content-Type-Options = "nosniff"
    Referrer-Policy = "strict-origin-when-cross-origin"
    Permissions-Policy = "camera=(), microphone=(), geolocation=()"

[[headers]]
  for = "/assets/*"
  [headers.values]
    Cache-Control = "public, max-age=31536000, immutable"
`;
  files.push({
    path: "netlify.toml",
    content: netlifyToml,
    contentType: "text/plain",
  });

  // 2. Vercel: vercel.json
  const vercelJson = JSON.stringify(
    {
      cleanUrls: true,
      trailingSlash: false,
      headers: [
        {
          source: "/(.*)",
          headers: [
            { key: "X-Frame-Options", value: "DENY" },
            { key: "X-Content-Type-Options", value: "nosniff" },
            { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          ],
        },
        {
          source: "/assets/(.*)",
          headers: [
            { key: "Cache-Control", value: "public, max-age=31536000, immutable" },
          ],
        },
      ],
    },
    null,
    2
  );
  files.push({
    path: "vercel.json",
    content: vercelJson,
    contentType: "application/json",
  });

  // 3. Cloudflare Pages: _headers
  const cloudflareHeaders = `# Cloudflare Pages Headers (TDD §21.2)
/*
  X-Frame-Options: DENY
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()

/assets/*
  Cache-Control: public, max-age=31536000, immutable
`;
  files.push({
    path: "_headers",
    content: cloudflareHeaders,
    contentType: "text/plain",
  });

  // 4. GitHub Pages: .nojekyll
  files.push({
    path: ".nojekyll",
    content: "",
    contentType: "text/plain",
  });

  // 5. Apache: .htaccess
  const htaccess = `# Apache Clean URLs & Gzip Compression
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteCond %{REQUEST_FILENAME}.html -f
  RewriteRule ^(.*)$ $1.html [L]
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/plain text/xml text/css application/javascript application/json
</IfModule>
`;
  files.push({
    path: ".htaccess",
    content: htaccess,
    contentType: "text/plain",
  });

  // 6. Nginx: nginx.conf snippet
  const nginxConf = `# Nginx Server Block Snippet for Static Site
server {
    listen 80;
    server_name example.com;
    root /var/www/html;
    index index.html;

    location / {
        try_files $uri $uri.html $uri/ /index.html =404;
    }

    location ~* \\.(?:css|js|jpg|jpeg|gif|png|ico|svg|webp)$ {
        expires 1y;
        add_header Cache-Control "public, max-age=31536000, immutable";
    }
}
`;
  files.push({
    path: "nginx.conf",
    content: nginxConf,
    contentType: "text/plain",
  });

  // 7. Comprehensive README.md
  const readme = generateDeploymentReadme(config, routes);
  files.push({
    path: "README.md",
    content: readme,
    contentType: "text/markdown",
  });

  return files;
}

function generateDeploymentReadme(config: SiteConfiguration, routes: string[]): string {
  return `# ${config.businessProfile.name} — Static Website Package

> **Generated by Fortress AI Export Pipeline (TDD v1.0, FR-080)**  
> **Platform Version**: \`1.0.0\`  
> **Export Date**: \`${new Date().toISOString()}\`  
> **Zero Platform Runtime Required**: Deploy directly to any static web host or CDN.

---

## Package Overview

This directory contains pure static HTML, CSS stylesheets, vanilla JavaScript, and media assets compiled from your canonical website configuration. It requires **zero Node.js runtime, zero build tools, and zero database connections**.

### Included Routes
${routes.map((r) => `- \`${r === "/" ? "/ (index.html)" : `${r} (${r.replace(/^\//, "")}.html)`}\``).join("\n")}

### Directory Structure
\`\`\`
.
├── index.html               # Homepage
${routes
  .filter((r) => r !== "/")
  .map((r) => `├── ${r.replace(/^\//, "")}.html`)
  .join("\n")}
├── assets/
│   ├── style.css            # Pre-compiled design tokens & responsive CSS
│   ├── app.js               # Accessible mobile nav & FAQ accordion handlers
│   └── images/              # Local media & SVG placeholders
├── sitemap.xml              # Search engine XML sitemap
├── robots.txt               # Crawler directives
├── manifest.json            # Machine-readable compilation manifest (TDD §40.6)
├── dependencies.json        # Backend feature status & resolution notes
├── DEPENDENCY_REPORT.md     # Full compatibility report
├── _redirects               # Netlify clean URLs configuration
├── netlify.toml             # Netlify deployment & security headers
├── vercel.json              # Vercel clean URLs configuration
├── _headers                 # Cloudflare Pages security headers
├── .nojekyll                # GitHub Pages bypass flag
├── .htaccess                # Apache web server rewrite rules
└── nginx.conf               # Nginx server configuration snippet
\`\`\`

---

## Deployment Quickstart

### 1. Netlify (Recommended for 1-minute launch)
1. Log in to [Netlify](https://app.netlify.com).
2. Go to **Sites** and drag & drop this entire unzipped folder into the Netlify drop zone.
3. Your site is live immediately with SSL and clean URLs!

### 2. Vercel
1. Install Vercel CLI: \`npm install -g vercel\`
2. In this folder, run: \`vercel --prod\`
3. Follow the CLI prompts. The included \`vercel.json\` configures clean URLs automatically.

### 3. Cloudflare Pages
1. Go to the Cloudflare dashboard -> **Workers & Pages**.
2. Select **Pages** -> **Create a project** -> **Upload assets**.
3. Drag and drop this folder and click **Deploy**.

### 4. GitHub Pages
1. Push these files to the \`gh-pages\` branch or \`/docs\` folder of your GitHub repository.
2. Under Repository **Settings** -> **Pages**, choose the branch as source.
3. The included \`.nojekyll\` file ensures all files are served properly.

### 5. Traditional VPS (Nginx / Apache / AWS S3)
- **Nginx**: Copy files to \`/var/www/html\` and refer to the included \`nginx.conf\`.
- **Apache**: Copy files to your web root; the included \`.htaccess\` handles clean URLs.
- **AWS S3 + CloudFront**: Upload all files to an S3 bucket configured for static web hosting.

---

## Backend Services & Contact Forms

Please review \`DEPENDENCY_REPORT.md\` for details on external integrations (e.g. connecting Formspree, Basin, or your own webhook to contact form fields).
`;
}
